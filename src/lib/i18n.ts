const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, ar };

/** Resolve the language synchronously at load so the very first frame is already in the right language. */
function detectInitialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    const stored = window.localStorage.getItem("fellogram.locale");
    if (stored === "ar" || stored === "en") return stored;
  } catch {
    /* storage can be blocked: fall through to detection */
  }
  const telegramUser = (window as unknown as { Telegram?: { WebApp?: { initDataUnsafe?: { user?: { language_code?: string } } } } }).Telegram?.WebApp?.initDataUnsafe?.user;
  const detected = telegramUser?.language_code ?? window.navigator.language ?? "en";
  return detected.toLowerCase().startsWith("ar") ? "ar" : "en";
}

let locale: Locale = detectInitialLocale();

function applyDocumentLocale() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
}

applyDocumentLocale();

export function getLocale(): Locale {
  return locale;
}

export function initializeLocale(telegramLanguage?: string | null) {
  if (typeof window === "undefined") return locale;
  const stored = window.localStorage.getItem("fellogram.locale");
  const detected = telegramLanguage ?? window.navigator.language;
  locale = stored === "ar" || stored === "en" ? stored : detected.toLowerCase().startsWith("ar") ? "ar" : "en";
  applyDocumentLocale();
  return locale;
}

const localeListeners = new Set<() => void>();

/** Lets React re-render the whole UI when the language changes (see useLocale). */
export function subscribeLocale(listener: () => void) {
  localeListeners.add(listener);
  return () => {
    localeListeners.delete(listener);
  };
}

export function setLocale(next: Locale) {
  locale = next;
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem("fellogram.locale", next);
    } catch {
      /* storage can be blocked: the choice then lasts for this session only */
    }
  }
  applyDocumentLocale();
  localeListeners.forEach((listener) => listener());
}

export function t(key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[locale][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
